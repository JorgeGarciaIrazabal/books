#!/usr/bin/env python3
"""Assemble verified narration segments into local chapter MP3s.

ASR/silence flags are not automatically errors, but they must be explicitly
adjudicated in a JSON list after listening. This tool does not publish files.
"""
import argparse, hashlib, json, subprocess
from pathlib import Path


def sha(path):
    h=hashlib.sha256()
    with path.open('rb') as f:
        for chunk in iter(lambda:f.read(1024*1024),b''): h.update(chunk)
    return h.hexdigest()


def main():
    p=argparse.ArgumentParser(description=__doc__)
    p.add_argument('segments',type=Path); p.add_argument('audio',type=Path)
    p.add_argument('checks',type=Path); p.add_argument('out',type=Path)
    p.add_argument('--adjudicated',type=Path,help='JSON array of segment IDs verified by a listener')
    a=p.parse_args()
    source=json.loads(a.segments.read_text()); checks=json.loads(a.checks.read_text())['segments']
    rows=source['pages']; numbers=[r['page'] for r in rows]; examined=[r['page'] for r in checks]
    if len(set(examined))!=len(examined) or examined!=numbers:
        raise SystemExit('Checks do not cover every segment in source order exactly once')
    approved=set(json.loads(a.adjudicated.read_text())) if a.adjudicated else set()
    unresolved=[r['page'] for r in checks if r['needs_listen'] and r['page'] not in approved]
    if unresolved: raise SystemExit(f'Unadjudicated ASR/pause flags: {unresolved}')
    expected={f"page-{n:02d}.wav" for n in numbers}; actual={x.name for x in a.audio.glob('page-*.wav')}
    if expected!=actual: raise SystemExit(f'Missing {sorted(expected-actual)}; extra {sorted(actual-expected)}')
    a.out.mkdir(parents=True,exist_ok=True); result=[]
    for ch in source['chapters']:
        chapter_rows=[r for r in rows if r['chapter']==ch['chapter']]
        # WAV inputs generated by the same engine share sample rate and channels.
        input_args=[]; labels=[]
        for i,row in enumerate(chapter_rows):
            input_args+=['-i',str((a.audio/f"page-{row['page']:02d}.wav").resolve())]; labels.append(f'[{i}:a]')
        dest=a.out/f"chapter-{ch['chapter']:02d}.mp3"
        filter_text=''.join(labels)+f'concat=n={len(labels)}:v=0:a=1[out]'
        subprocess.run(['ffmpeg','-nostdin','-hide_banner','-loglevel','error','-y',*input_args,'-filter_complex',filter_text,'-map','[out]','-ac','1','-b:a','128k',str(dest)],check=True)
        duration=float(subprocess.run(['ffprobe','-v','error','-show_entries','format=duration','-of','default=nw=1:nk=1',str(dest)],capture_output=True,text=True,check=True).stdout)
        result.append({'chapter':ch['chapter'],'title':ch['title'],'path':dest.name,'segments':[r['page'] for r in chapter_rows],'sha256':sha(dest),'seconds':round(duration,3)})
        print(f"{dest.name}: {duration:.1f}s",flush=True)
    (a.out/'chapters.json').write_text(json.dumps({'schema_version':1,'status':'private audio; listening review required','chapters':result},ensure_ascii=False,indent=2)+'\n')

if __name__=='__main__': main()
